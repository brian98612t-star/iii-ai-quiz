"""
Assemble and Validate 400 Questions + 80 Must-Memorize Questions
Clean up all parenthetical hints/giveaways so no option leaks the answer!
"""
import json
import random
import os
import sys
import re

from data_module1 import get_module1_questions
from data_module2 import get_module2_questions
from data_module3 import get_module3_questions
from data_module4 import get_module4_questions

def clean_option_text(opt):
    """
    Remove giveaway parentheses from option text.
    Preserves mathematical probabilities like P(y|x) where all 4 options share the formula.
    """
    # Preserve math probabilities: P(y|x), P(x, y), P(x), P(x|y)
    if re.search(r'P\([xy\|\s,]+\)', opt):
        return opt.strip()
    
    # Remove all parentheses and their contents (including nested ones)
    cleaned = opt
    while re.search(r'[\(（][^)）]+[\)）]', cleaned):
        cleaned = re.sub(r'[\(（][^)）]+[\)）]', '', cleaned).strip()
    
    return cleaned if cleaned else opt.strip()

def assemble():
    m1 = get_module1_questions()
    m2 = get_module2_questions()
    m3 = get_module3_questions()
    m4 = get_module4_questions()

    print(f"Loaded modules: M1={len(m1)}, M2={len(m2)}, M3={len(m3)}, M4={len(m4)}")
    all_raw = m1 + m2 + m3 + m4
    assert len(all_raw) == 400, f"Expected 400 questions, got {len(all_raw)}"

    balanced_questions = []
    answer_dist = {0: 0, 1: 0, 2: 0, 3: 0}

    for raw_q in all_raw:
        qid = raw_q["id"]
        raw_opts = raw_q["options"]
        orig_ans_idx = raw_q["answer"]
        
        # Clean giveaway parentheses from all options
        cleaned_opts = [clean_option_text(o) for o in raw_opts]
        
        # Ensure no duplicates after cleaning
        assert len(set(cleaned_opts)) == 4, f"Q{qid} has duplicate options after cleaning: {cleaned_opts}"
        
        correct_text = cleaned_opts[orig_ans_idx]

        # Use deterministic random seed per question id to balance answer positions
        rng = random.Random(qid * 7919 + 104729)
        shuffled_indices = [0, 1, 2, 3]
        rng.shuffle(shuffled_indices)

        new_opts = [cleaned_opts[i] for i in shuffled_indices]
        new_ans_idx = new_opts.index(correct_text)
        answer_dist[new_ans_idx] += 1

        new_q = {
            "id": qid,
            "category": raw_q["category"],
            "tags": raw_q.get("tags", []),
            "isMustMemorize": raw_q.get("isMustMemorize", False),
            "question": raw_q["question"],
            "options": new_opts,
            "answer": new_ans_idx,
            "explanation": raw_q["explanation"]
        }
        balanced_questions.append(new_q)

    print("Answer distribution across (A, B, C, D):",
          {["A", "B", "C", "D"][k]: v for k, v in answer_dist.items()})

    # Separate out 80 must-memorize questions
    must_memorize = [q for q in balanced_questions if q["isMustMemorize"]]
    print(f"Total Must-Memorize Questions: {len(must_memorize)}")
    assert len(must_memorize) == 80, f"Expected 80 must-memorize questions, got {len(must_memorize)}"

    # Re-index must-memorize questions to 1..80 for standalone 80-question test
    standalone_80 = []
    for idx, q in enumerate(must_memorize, 1):
        q_copy = dict(q)
        q_copy["originalId"] = q["id"]
        q_copy["standaloneId"] = idx
        standalone_80.append(q_copy)

    dest_dir = r"C:\Users\Desktop_weee\.gemini\antigravity\scratch\iii_quiz_app"
    os.makedirs(dest_dir, exist_ok=True)

    # 1. Output questions.js
    js_content = f"""// Auto-generated by assemble_bank.py
// Total questions: 400 | Must-memorize questions: 80
// Parentheses giveaway issues resolved 100%

const MUST_MEMORIZE_80 = {json.dumps(standalone_80, ensure_ascii=False, indent=2)};

const ALL_QUESTIONS_400 = {json.dumps(balanced_questions, ensure_ascii=False, indent=2)};

// Legacy compatibility
const QUESTIONS_DATA = MUST_MEMORIZE_80;
"""
    with open(os.path.join(dest_dir, "questions.js"), "w", encoding="utf-8") as f:
        f.write(js_content)
    print("Successfully wrote questions.js")

    # 2. Output questions_bank_400.json
    with open(os.path.join(dest_dir, "questions_bank_400.json"), "w", encoding="utf-8") as f:
        json.dump(balanced_questions, f, ensure_ascii=False, indent=2)
    print("Successfully wrote questions_bank_400.json")

    # 3. Output questions_must_memorize_80.json
    with open(os.path.join(dest_dir, "questions_must_memorize_80.json"), "w", encoding="utf-8") as f:
        json.dump(standalone_80, f, ensure_ascii=False, indent=2)
    print("Successfully wrote questions_must_memorize_80.json")

    # 4. Generate Markdown Study Guide in Artifact Directory
    artifact_path = r"C:\Users\Desktop_weee\.gemini\antigravity\brain\2520f866-1fee-41aa-a9ef-419ecbcb3b55\iii_must_memorize_80_glossary.md"
    letters = ["A", "B", "C", "D"]
    with open(artifact_path, "w", encoding="utf-8") as f:
        f.write("# 資策會「生成式 AI 能力認證」必背高頻專有名詞 80 題精選速記題庫\n\n")
        f.write("> **核心說明**：本題庫專為考前衝刺鎖定，已徹底去除選項中的暗示性括弧與洩題贅字，選項格式高度對齊標準正式檢定規範。\n\n")
        f.write("---\n\n")
        
        current_cat = ""
        for q in standalone_80:
            if q["category"] != current_cat:
                current_cat = q["category"]
                f.write(f"\n## 模組專區：{current_cat}\n\n")
            f.write(f"### 第 {q['standaloneId']} 題（全庫第 {q['originalId']} 題）\n")
            f.write(f"**題目**：{q['question']}\n\n")
            for i, opt in enumerate(q["options"]):
                prefix = f"**({letters[i]})**" if i == q["answer"] else f"({letters[i]})"
                f.write(f"* {prefix} {opt}\n")
            f.write(f"\n> **標準答案**：**({letters[q['answer']]})**\n")
            f.write(f"> **考點解析**：{q['explanation']}\n\n---\n\n")

    print(f"Successfully generated Markdown Study Guide at: {artifact_path}")

if __name__ == "__main__":
    assemble()
